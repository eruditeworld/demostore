// ===== BUSINESS SETTINGS =====
const UPI_CONFIG = {
    upiId: "nabilakhan9311@okicici",
    payeeName: "Nabila Khan",
    currency: "INR"
};

/**
 * Generates a dynamic UPI Payment URI for mobile apps and QR code scanning.
 * @param {number|string} amount - Total amount in INR
 * @param {string} transactionId - Unique Order ID or Enrollment ID (e.g. NK-20260928-001)
 * @returns {string} Fully encoded UPI payment URI
 */
function generateUPILink(amount, transactionId) {
    const upiId = UPI_CONFIG.upiId;
    const name = UPI_CONFIG.payeeName;
    const cleanAmount = parseFloat(amount).toFixed(2);

    return `upi://pay?pa=${encodeURIComponent(upiId)}&pn=${encodeURIComponent(name)}&am=${encodeURIComponent(cleanAmount)}&cu=${encodeURIComponent(UPI_CONFIG.currency)}&tn=${encodeURIComponent(transactionId)}`;
}

/**
 * Returns a high-resolution QR code image URL for scanning on another device.
 * @param {string} upiUri - The complete UPI URI generated by generateUPILink
 * @returns {string} URL to load the QR code image
 */
function generateUPIQRCodeURL(upiUri) {
    // Encodes standard UPI URI into QR code image
    return `https://api.qrserver.com/v1/create-qr-code/?size=260x260&margin=10&data=${encodeURIComponent(upiUri)}`;
}

/**
 * Copies the business UPI ID to clipboard with tactile feedback.
 * @param {string} buttonElementId - Optional element ID to update state
 * @returns {Promise<boolean>}
 */
async function copyUPIID(buttonElementId) {
    const upiText = UPI_CONFIG.upiId;
    let copied = false;

    if (navigator.clipboard && navigator.clipboard.writeText) {
        try {
            await navigator.clipboard.writeText(upiText);
            copied = true;
        } catch (err) {
            console.warn("Clipboard API failed, trying fallback textarea", err);
        }
    }

    if (!copied) {
        const textarea = document.createElement("textarea");
        textarea.value = upiText;
        textarea.style.position = "fixed";
        textarea.style.opacity = "0";
        document.body.appendChild(textarea);
        textarea.select();
        try {
            copied = document.execCommand("copy");
        } catch (e) {
            copied = false;
        }
        document.body.removeChild(textarea);
    }

    if (buttonElementId) {
        const btn = document.getElementById(buttonElementId);
        if (btn) {
            const originalText = btn.innerHTML;
            btn.innerHTML = `<svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5"><polyline points="20 6 9 17 4 12"/></svg> Copied: ${upiText}`;
            btn.classList.add("copied");
            setTimeout(() => {
                btn.innerHTML = originalText;
                btn.classList.remove("copied");
            }, 2500);
        }
    }

    if (typeof showToast === 'function') {
        showToast("UPI ID copied: " + upiText, "success");
    }

    return copied;
}

